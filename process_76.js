function parseData(text) {
  const chunks = text.trim().split(/\n\n+/);
  const result = [];
  
  for (const chunk of chunks) {
    const lines = chunk.trim().split('\n').map(l => l.trim()).filter(l => l);
    if (!lines.length) continue;
    
    const reqNo = lines[0];
    let hinmei = null;
    let parts = [];
    
    if (lines.length === 2 && lines[1] === '(Blueprint)') {
      // Blueprint, skip or emit? Usually we skip blueprints if they don't have BOM, 
      // but let's include them with null/empty components to be safe.
    } else if (lines.length >= 2) {
      hinmei = lines[1];
      if (lines.length >= 3) {
        if (lines[2] !== '(No BOM section at all)' && lines[2] !== '(No BOM)') {
          parts = lines[2].split(',').map(s => s.trim()).filter(s => s);
        }
      }
    }
    
    if (hinmei) {
      result.push({
        request_no: reqNo,
        hinmei: hinmei,
        components: parts.map(p => ({ part_no: p }))
      });
    }
  }
  return result;
}

